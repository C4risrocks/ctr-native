"""A Mac app of one 3DS game: launches Azahar with the game and its own sandbox.

The generated bundle (mirroring nxnative's `pack_app.py`):

    <name>.app/
      Info.plist                 CFBundleName from the SMDH title, icon, id, versions
      ctr-native                 the double-clickable launcher (a tiny script)
      Resources/AppIcon.icns     the SMDH icon, through macOS's own sips + iconutil
      Resources/ctr-native/      overlay records: config snapshot, profile hash
      Contents/MacOS/sandbox/    Azahar's user directory for this game. Azahar uses
                                 a `user/` folder inside its working directory
                                 (`SetUserDirectory`, file_util.cpp), so the
                                 launcher drops the cwd into `sandbox/`: config,
                                 nand, sdmc, cache and log all live here — saves
                                 included, isolated per game.

Reusing a build: `ctr-native.key` records the packed inputs (ROM hash, Azahar
binary stamp, profile hash, icon hash); while it matches and the bundle exists,
nothing is rewritten — the sandbox, and therefore the save, is never touched.
Console keys never enter a bundle and no game content enters git (.gitignore);
the sandbox holds user data only (saves, logs, shader caches).
"""

from __future__ import annotations

import hashlib
import plistlib
import subprocess  # codesign/iconutil/sips: macOS tools, fixed paths, no shell
import time
import zlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from collections.abc import Callable

LAUNCHER_NAME = "ctr-native"
KEY_NAME = "ctr-native.key"
SANDBOX_REL = Path("MacOS/sandbox")
ICON_SIZES = (16, 32, 64, 128, 256, 512)


class PackError(Exception):
    """A bundle that cannot be built or refreshed."""


# bundle layout helpers ------------------------------------------------------

def contents_of(app: Path) -> Path:
    return app / "Contents"


def sandbox_of(app: Path) -> dict[str, Path]:
    """Where this game's data lives. On macOS Azahar resolves every user path
    under $HOME (`LaunchQtFrontend` chdirs to its own bundle, so a cwd-side
    `user/` is unreachable — the portable-user path is Linux-only), so the
    launcher runs Azahar with HOME pointed inside the bundle: everything
    (config, nand, sdmc, cache, log) lands under `sandbox/home/Library/...`
    and never touches your global Azahar configuration."""
    sandbox = contents_of(app) / SANDBOX_REL
    home = sandbox / "home"
    app_data = home / "Library/Application Support/Azahar"
    return {
        "sandbox": sandbox,
        "home": home,
        "user": app_data,
        "config": app_data / "config",
        "nand": app_data / "nand",
        "sdmc": app_data / "sdmc",
        "log": app_data / "log",
        "cache": app_data / "cache",
    }


def ensure_sandbox(app: Path) -> None:
    for path in sandbox_of(app).values():
        path.mkdir(parents=True, exist_ok=True)


def write_atomic(path: Path, payload: bytes) -> None:
    """tmp + rename: a killed build never leaves half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_bytes(payload)
    tmp.replace(path)


def stage_file(path: Path, payload: bytes, only_changed: bool = True) -> bool:
    """Write through a temp when the content differs; report whether anything was written."""
    if only_changed and path.exists() and path.read_bytes() == payload:
        return False
    write_atomic(path, payload)
    return True


# content builders -----------------------------------------------------------

def launcher_text(azahar_bin: Path, rom_path: Path, sandbox_dir: Path,
                  language: str, tool_version: str) -> str:
    """The launcher script: one cd, then exec — every path absolute by design.

    `open` (and Finder) may hand the launcher a relative argv[0]; a cwd-side
    sandbox would then silently land Azahar in its *global* configuration
    instead of this app's own. nxnative bakes paths the same way: a moved
    bundle rebuilds, the game's data does not follow it.
    """
    def quote(value: Any) -> str:
        return "'" + str(value).replace("'", "'\\''") + "'"

    return "\n".join([
        "#!/bin/bash",
        "# Generated by ctr-native — do not edit; rebuild instead.",
        f"# language: {language} · toolkit: {tool_version}",
        f"AZAHAR={quote(azahar_bin)}",
        f"ROM={quote(rom_path)}",
        f"HOME={quote(sandbox_dir / 'home')}",
        'mkdir -p "$HOME"',
        'exec "$AZAHAR" -f "$ROM"',
        "",
    ])


def info_plist(app_name: str, bundle_id: str, version: str) -> bytes:
    data: dict[str, Any] = {
        "CFBundleDevelopmentRegion": "English",
        "CFBundleExecutable": LAUNCHER_NAME,
        "CFBundleIconFile": "AppIcon",
        "CFBundleIdentifier": bundle_id,
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": app_name,
        "CFBundleDisplayName": app_name,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "CFBundleAllowMixedLocalizations": True,
    }
    return plistlib.dumps(data)


def schema_hash(items: dict[str, str]) -> str:
    digest = hashlib.sha256()
    for key in sorted(items):
        digest.update(key.encode())
        digest.update(b"=")
        digest.update(items[key].encode())
        digest.update(b"\x00")
    return digest.hexdigest()


def app_bundle_id(title_id: str) -> str:
    return f"org.ctrnative.{title_id.lower()}"


# icon -----------------------------------------------------------------------

def app_name_from_smdh(long_title: str) -> str:
    """Filesystem-safe app name (Finder refuses ':' inside file names)."""
    cleaned = long_title.strip().replace(":", " -").replace("/", "-")[:120].strip() or "Game"
    return cleaned


class IconSet:
    """SMDH icon -> AppIcon.icns with the macOS builtins sips + iconutil only.

    The 48x48 SMDH icon is written as a PNG with the standard-library zlib
    (no dependencies), then sips resamples the sizes iconutil needs and the
    .icns gets built. Both tools ship with macOS, so icon work adds nothing
    external to the pipeline.
    """

    def __init__(self, iconset_dir: Path) -> None:
        self.iconset_dir = iconset_dir

    def refresh(self, pixels: list[tuple[int, int, int, int]], width: int, height: int) -> Path | None:
        iconset_dir = self.iconset_dir.with_name(self.iconset_dir.name + ".iconset")
        iconset_dir.mkdir(parents=True, exist_ok=True)
        for stale_png in iconset_dir.glob("*.png"):
            stale_png.unlink()
        source = iconset_dir / "icon_512x512.png"
        source.write_bytes(png_bytes(pixels, width, height, upsample=True))
        results = []
        for size in ICON_SIZES:
            target = iconset_dir / f"icon_{size}x{size}.png"
            if not resample(source, size, target):
                results = []
                break
            results.append(target)
        if not results:
            return None
        for clean in iconset_dir.glob("icon_512x512.png"):
            clean.unlink()
        icns = self.iconset_dir.parent / "AppIcon.icns"
        icns_tmp = icns.with_suffix(".tmp.icns")
        try:
            subprocess.run(
                ["/usr/bin/iconutil", "-c", "icns", str(iconset_dir), "-o", str(icns_tmp)],
                check=True, capture_output=True,
            )
        except (OSError, subprocess.SubprocessError) as error:
            raise PackError(f"iconutil failed: {error}") from error
        icns_tmp.replace(icns)
        return icns if icns.exists() else None


def png_bytes(pixels: list[tuple[int, int, int, int]], width: int, height: int, upsample: bool = False) -> bytes:
    """A minimal RGBA PNG writer (stdlib zlib); nearest-neighbour 48 -> 512 for crisp docks."""
    if upsample:
        pixels = resize_nearest(pixels, width, height, 512, 512)
        width = height = 512
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for (r, g, b, _a) in pixels[y * width : (y + 1) * width]:
            rows += bytes((r, g, b, 255))
    def chunk(kind: bytes, data: bytes) -> bytes:
        return len(data).to_bytes(4, "big") + kind + data + zlib.crc32(kind + data).to_bytes(4, "big")
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", width.to_bytes(4, "big") + height.to_bytes(4, "big") + bytes((8, 6, 0, 0, 0)))
            + chunk(b"IDAT", zlib.compress(bytes(rows), 9))
            + chunk(b"IEND", b""))


def resize_nearest(
    pixels: list[tuple[int, int, int, int]], width: int, height: int, new_width: int, new_height: int
) -> list[tuple[int, int, int, int]]:
    out: list[tuple[int, int, int, int]] = []
    for y in range(new_height):
        sy = min(y * height // new_height, height - 1)
        for x in range(new_width):
            sx = min(x * width // new_width, width - 1)
            out.append(pixels[sy * width + sx])
    return out


def resample(source: Path, size: int, target: Path) -> bool:
    try:
        subprocess.run(
            ["/usr/bin/sips", "-z", str(size), str(size), str(source), "--out", str(target)],
            check=True, capture_output=True,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return target.exists()


# signing --------------------------------------------------------------------

def codesign(app: Path, identity: str = "-", say: Callable[[str], None] | None = None) -> None:
    """Ad-hoc sign (or Developer ID with --mac-sign) so a double-click just works."""
    cmd = ["/usr/bin/codesign", "--force", "--deep", "--sign", identity, str(app)]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode:
        raise PackError(f"codesign failed: {result.stderr.strip()}")
    if say:
        say(f"signed ({identity or 'ad-hoc'})")


# the pack stage -------------------------------------------------------------

@dataclass
class PackInputs:
    """Everything that decides whether a rebuild changes the bundle."""

    rom_path: Path
    whom: Path  # the bundle being packed (sandbox paths are part of its signature)
    azahar_bin: Path
    azahar_version: str
    toolkit_version: str
    profile_hash: str
    icon_png: bytes | None
    launcher_args: list[str]  # extra argv for the launcher (e.g. env-style config)

    @property
    def sandbox_dir(self) -> Path:
        return self.whom / SANDBOX_REL


def pack(
    app: Path,
    app_name: str,
    title_id: str,
    version: str,
    language: str,
    inputs: PackInputs,
    icon_pixels: list[tuple[int, int, int, int]] | None,
    icon_size: tuple[int, int],
    sign_identity: str = "-",
    say: Callable[[str], None] = print,
) -> bool:
    """Build or refresh `app`; returns True when it came from the reuse key."""
    contents = contents_of(app)
    macos, resources = contents / "MacOS", contents / "Resources"
    key_path = resources / "ctr-native" / KEY_NAME
    signature = pack_inputs_hash(inputs, icon_pixels)

    if app.exists() and key_path.exists() and key_path.read_text().strip() == signature:
        say(f"app packed (inputs unchanged): {app.name}")  # sandbox untouched: saves stay
        return True
    started = time.monotonic()

    ensure_sandbox(app)
    icon_file: Path | None = None
    if icon_pixels:
        iconset = IconSet(resources / "ctr-native" / "iconset")
        icon_file = iconset.refresh(icon_pixels, icon_size[0], icon_size[1])

    write_atomic(macos / LAUNCHER_NAME, launcher_text(
        inputs.azahar_bin, inputs.rom_path, sandbox_of(app)["sandbox"], language, inputs.toolkit_version,
    ).encode())
    (macos / LAUNCHER_NAME).chmod(0o755)
    write_atomic(contents / "Info.plist", info_plist(app_name, app_bundle_id(title_id), version))

    overlay_dir = resources / "ctr-native"
    overlay_dir.mkdir(parents=True, exist_ok=True)
    if icon_file is not None:
        write_atomic(overlay_dir / "icon.stamp", signature.encode())
    write_atomic(overlay_dir / KEY_NAME, (signature + "\n").encode())
    write_atomic(overlay_dir / "inputs.tsv", "".join(
        f"{line}\n" for line in [
            f"azahar_version\t{inputs.azahar_version}",
            f"toolkit_version\t{inputs.toolkit_version}",
            f"language\t{language}",
            f"profile_hash\t{inputs.profile_hash}",
            f"appid\t{app_bundle_id(title_id)}",
            f"icon\t{'yes' if icon_pixels else 'SMDH-missing'}",
        ]).encode())

    codesign(app, sign_identity, say=say)
    say(f"app packed in {int(time.monotonic() - started)}s: {app}")
    return False


def pack_inputs_hash(inputs: PackInputs, icon_pixels: list[tuple[int, int, int, int]] | None) -> str:
    return schema_hash({
        "rom": hash_file(inputs.rom_path),
        "azahar": file_stamp(inputs.azahar_bin),
        "profile": inputs.profile_hash,
        "toolkit": inputs.toolkit_version,
        "launcher": schema_hash({
            "text": launcher_text(inputs.azahar_bin, inputs.rom_path,
                                  inputs.sandbox_dir, "en", inputs.toolkit_version),
        }),
        "launcher_args": schema_hash({str(index): value for index, value in enumerate(inputs.launcher_args)}),
        "icon": "none" if icon_pixels is None else "present",
    })


def file_stamp(path: Path) -> str:
    stat = path.stat()
    return f"{stat.st_size}:{stat.st_mtime_ns}"


def hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb", buffering=0) as file:
        while chunk := file.read(0x100_0000):
            digest.update(chunk)
    return digest.hexdigest()
